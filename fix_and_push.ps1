        <h2>1. Purpose and scope</h2>
        <p>
          This report describes how rental housing enforcement authority is structured in Seattle, how it appears in public documentation and budgets, and how it compares in broad terms with enforcement approaches in other large U.S. cities. It is written in a neutral, oversight‑style tone and is intended to support discussion by residents, policymakers, and oversight bodies.
        </p>
        <p class="muted">
          The analysis focuses on three questions: (1) what tools and penalties are available on paper, (2) what public data suggest about the use of those tools, and (3) how selected peer‑city frameworks handle fines and enforcement.
        </p>

        <h2>2. Seattle housing enforcement framework</h2>
        <h3>2.1 Rental Registration and Inspection Ordinance (RRIO)</h3>
        <p>
          The City of Seattle regulates rental properties through the Seattle Department of Construction &amp; Inspections (SDCI), including the Rental Registration and Inspection Ordinance (RRIO). RRIO requires rental property owners to register their properties, maintain them to minimum housing standards, and participate in periodic inspections. Public guidance for owners and managers describes these requirements and processes. <a href="https://www.seattle.gov/sdci/codes/licensing-and-registration/rental-registration-and-inspection-ordinance/owners-and-managers" target="_blank" rel="noopener">RRIO owners &amp; managers page</a> [web:3].
        </p>
        <p>
          That guidance also notes that owners who do not register by the due date, do not complete required inspections, or rent units that do not meet minimum standards may receive violations. It specifies that penalties for certain violations are <strong>$150 per day for the first 10 days and $500 per day after that</strong> when issues remain uncorrected. <a href="https://www.seattle.gov/sdci/codes/licensing-and-registration/rental-registration-and-inspection-ordinance/owners-and-managers" target="_blank" rel="noopener">RRIO owners &amp; managers page</a> [web:3].
        </p>

        <h3>2.2 Penalties and violations</h3>
        <p>
          SDCI’s RRIO violations and penalties flyer explains that once a Notice of Violation is issued, penalties begin to accrue if the violation is not corrected by the compliance date. It also describes the process for referring unresolved cases to the City Attorney’s Office to seek compliance and recover penalties, and outlines options for requesting penalty reductions and appealing a notice. <a href="https://www.seattle.gov/documents/Departments/SDCI/Codes/RRIO/RRIOViolationsandPenaltiesFlyer-a_173567.pdf" target="_blank" rel="noopener">RRIO violations and penalties flyer (PDF)</a> [web:6].
        </p>
        <p class="muted">
          These materials show that the City has authority to impose and pursue escalating penalties for non‑compliance, though they do not indicate how often penalties are reduced, waived, or collected in full.
        </p>

        <h3>2.3 Program reporting and budget context</h3>
        <p>
          The City Auditor’s review of RRIO and SDCI budget and fee information provide context for how the program is funded, including registration fees, inspection fees, and technology surcharges. For example, a fiscal note and subsequent audit work describe how RRIO revenue estimates are developed and how fee levels relate to projected program costs. <a href="https://seattle.legistar.com/View.ashx?M=F&ID=6700510&GUID=33FC7AD7-4CF0-43DD-87F7-82EF7DFB5A6D" target="_blank" rel="noopener">RRIO fiscal note (PDF)</a> and <a href="https://www.seattle.gov/documents/departments/cityauditor/auditreports/rrioaudit.pdf" target="_blank" rel="noopener">RRIO program audit (PDF)</a> [web:23][web:24].
        </p>
        <p>
          RRIO reports and related documents show program activity and overall revenue, but fines and penalties appear as a relatively small component compared with registration and permit fees. This is consistent with the Auditor’s description of the fee model, which emphasizes fee‑based cost recovery rather than large penalty‑driven funding. <a href="https://www.seattle.gov/documents/departments/cityauditor/auditreports/rrioaudit.pdf" target="_blank" rel="noopener">RRIO program audit</a> [web:24].
        </p>

        <h2>3. Peer‑city enforcement reference points</h2>

        <h3>3.1 New York City</h3>
        <p>
          New York City’s Department of Housing Preservation and Development (HPD) publishes a detailed description of charges and fees, including complaint‑based inspection fees and charges for repair work performed by the city and billed to owners. For example, HPD may assess a $200 fee for certain complaint‑based inspections that result in hazardous or immediately hazardous violations, and unpaid charges can become tax liens. <a href="https://www.nyc.gov/site/hpd/services-and-information/hpd-charges-and-fees.page" target="_blank" rel="noopener">HPD charges and fees</a> [web:25].
        </p>
        <p>
          New York City also provides open data on housing litigations, describing actions that HPD brings in Housing Court against owners who fail to correct hazardous conditions. This dataset includes information on case types and status, illustrating how litigation is used as part of the enforcement toolkit. <a href="https://data.cityofnewyork.us/Housing-Development/Housing-Litigations/59kj-x8nc" target="_blank" rel="noopener">Housing Litigations – NYC Open Data</a> [web:7].
        </p>
        <p class="muted">
          An analysis of municipal fine collection in New York City, published in the Yale Law Journal Forum, finds that while large fines can be assessed, actual collection often depends on follow‑up practices and may be significantly lower than nominal totals. <a href="https://yalelawjournal.org/pdf/LazenbyEssay_7nutmikb.pdf" target="_blank" rel="noopener">“Who Pays? An Analysis of Fine Collection in New York City”</a> [web:26].
        </p>

        <h3>3.2 San Francisco</h3>
        <p>
          San Francisco’s Rent Board fee funds the cost of operating the Rent Board and is assessed per dwelling unit. Public guidance explains the per‑unit fee amount, how much of the fee landlords may pass through to tenants, and the schedule of penalties for late payment, including incremental 5 percent penalties and referral of delinquent accounts to the Bureau of Delinquent Revenue. <a href="https://sfrb.org/node/294" target="_blank" rel="noopener">Rent Board fee – Topic No. 013</a> [web:11].
        </p>
        <p>
          The San Francisco Public Works code specifies penalties for ordinance violations, including fines for infractions and misdemeanors, as well as civil penalties of up to $500 per day for continuing violations, which may be pursued by the City Attorney. <a href="https://codelibrary.amlegal.com/codes/san_francisco/latest/sf_publicworks/0-0-0-4268" target="_blank" rel="noopener">San Francisco Public Works Code § 811</a> [web:5].
        </p>
        <p>
          In addition, San Francisco’s rent ordinance enforcement provisions describe how certain landlord conduct, such as rent increases in violation of administrative decisions, may constitute separate violations for each month the conduct continues, providing a framework for ongoing enforcement. <a href="https://www.sf.gov/information--sec-3710a-misdemeanors-and-other-enforcement-provisions" target="_blank" rel="noopener">Rent Ordinance § 37.10A enforcement provisions</a> [web:8].
        </p>

        <h2>4. Financial implications and signals from public data</h2>
        <p>
          In Seattle, RRIO and related materials show that the City has the ability to impose per‑day penalties for certain rental housing violations, and to refer unresolved matters to the City Attorney to pursue compliance and penalties. At the same time, RRIO audit work and fiscal notes emphasize a fee‑based revenue model, and publicly visible revenue from fines and penalties remains limited relative to the potential implied by statutory penalty levels. <a href="https://www.seattle.gov/sdci/codes/licensing-and-registration/rental-registration-and-inspection-ordinance/owners-and-managers" target="_blank" rel="noopener">RRIO guidance</a>; <a href="https://www.seattle.gov/documents/Departments/SDCI/Codes/RRIO/RRIOViolationsandPenaltiesFlyer-a_173567.pdf" target="_blank" rel="noopener">RRIO penalties flyer</a>; <a href="https://www.seattle.gov/documents/departments/cityauditor/auditreports/rrioaudit.pdf" target="_blank" rel="noopener">RRIO audit</a> [web:3][web:6][web:24].
        </p>
        <p>
          Peer‑city examples in New York City and San Francisco show more explicit integration of penalties, litigation, and fee structures in publicly described enforcement systems. Published schedules and open data help illustrate how penalties are assessed, how often they are used, and how unpaid amounts may be escalated through tax liens or delinquent revenue procedures. <a href="https://www.nyc.gov/site/hpd/services-and-information/hpd-charges-and-fees.page" target="_blank" rel="noopener">HPD charges and fees</a>; <a href="https://data.cityofnewyork.us/Housing-Development/Housing-Litigations/59kj-x8nc" target="_blank" rel="noopener">Housing litigations</a>; <a href="https://sfrb.org/node/294" target="_blank" rel="noopener">SF Rent Board fee</a>; <a href="https://codelibrary.amlegal.com/codes/san_francisco/latest/sf_publicworks/0-0-0-4268" target="_blank" rel="noopener">SF Public Works penalties</a> [web:7][web:11][web:5][web:25].
        </p>
        <p class="muted">
          The Yale Law Journal analysis highlights that even in jurisdictions with robust penalty structures, realized collections can differ from assessed amounts, reinforcing the importance of tracking not only violations and penalties, but also collection rates and outcomes. <a href="https://yalelawjournal.org/pdf/LazenbyEssay_7nutmikb.pdf" target="_blank" rel="noopener">“Who Pays?”</a> [web:26].
        </p>

        <h2>5. Observations for oversight discussion</h2>
        <p>
          The public record suggests a difference between: (a) the scope of penalty authority described in Seattle’s RRIO enforcement materials, and (b) the relatively modest role that fines and penalties appear to play in overall program funding and publicly reported outcomes. Clarifying how often penalties are assessed, how frequently they are reduced or waived, and what share of assessed penalties is actually collected would help provide a more complete financial picture. <a href="https://www.seattle.gov/sdci/codes/licensing-and-registration/rental-registration-and-inspection-ordinance/owners-and-managers" target="_blank" rel="noopener">RRIO guidance</a>; <a href="https://www.seattle.gov/documents/Departments/SDCI/Codes/RRIO/RRIOViolationsandPenaltiesFlyer-a_173567.pdf" target="_blank" rel="noopener">RRIO penalties flyer</a>; <a href="https://www.seattle.gov/documents/departments/cityauditor/auditreports/rrioaudit.pdf" target="_blank" rel="noopener">RRIO audit</a> [web:3][web:6][web:24].
        </p>
        <p>
          Practices in New York City and San Francisco, including detailed penalty schedules, published fee frameworks, and open data on litigation and enforcement, provide reference points for how other jurisdictions present and use penalty tools. Any consideration of changes in Seattle would need to reflect local legal requirements and policy choices, but these examples may be useful for comparative assessment and for identifying potential reporting or transparency enhancements. <a href="https://www.nyc.gov/site/hpd/services-and-information/hpd-charges-and-fees.page" target="_blank" rel="noopener">HPD charges and fees</a>; <a href="https://data.cityofnewyork.us/Housing-Development/Housing-Litigations/59kj-x8nc" target="_blank" rel="noopener">Housing litigations</a>; <a href="https://sfrb.org/node/294" target="_blank" rel="noopener">SF Rent Board fee</a>; <a href="https://codelibrary.amlegal.com/codes/san_francisco/latest/sf_publicworks/0-0-0-4268" target="_blank" rel="noopener">SF Public Works penalties</a>; <a href="https://www.sf.gov/information--sec-3710a-misdemeanors-and-other-enforcement-provisions" target="_blank" rel="noopener">SF Rent Ordinance enforcement</a> [web:25][web:7][web:11][web:5][web:8].
        </p>
        <p class="callout">
          This report does not estimate precise “lost revenue” or assign responsibility for individual cases. It is limited to what can be supported by publicly available documents and highlights areas where additional internal data or explanations would be needed for a comprehensive financial assessment.
        </p>
